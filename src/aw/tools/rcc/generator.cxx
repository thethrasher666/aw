#include "generator.hxx"
#include "diagnosticx.hxx"

#include <algorithm>
#include <fstream>
#include <unordered_map>

namespace aw::rcc
{
    namespace
    {
        struct LoadedResource
        {
            std::string               path;
            std::vector<std::uint8_t> data;
        };

        auto readFile(std::filesystem::path const& path) -> std::optional<std::vector<std::uint8_t>>
        {
            std::ifstream input(path, std::ios::binary);
            if (!input.is_open())
            {
                return std::nullopt;
            }

            return std::vector<std::uint8_t>{ std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>() };
        }

        auto loadResources(Manifest const& manifest, std::filesystem::path const& baseDir, std::vector<LoadedResource>& loaded) -> bool
        {
            std::unordered_map<std::string, std::filesystem::path> claimed;
            bool                                                   ok = true;

            for (auto const& resource : manifest.resources)
            {
                auto const [claim, inserted] = claimed.try_emplace(resource.path, resource.source);
                if (!inserted)
                {
                    if (claim->second == resource.source)
                    {
                        continue;
                    }

                    logError("resource", resource.path, "is claimed by both", claim->second.string(), "and", resource.source.string());
                    ok = false;
                    continue;
                }

                auto data = readFile(baseDir / resource.source);
                if (!data)
                {
                    logError("cannot open", (baseDir / resource.source).string());
                    ok = false;
                    continue;
                }

                loaded.push_back(LoadedResource{ resource.path, *std::move(data) });
            }

            std::sort(loaded.begin(), loaded.end(), [](LoadedResource const& lhs, LoadedResource const& rhs) { return lhs.path < rhs.path; });
            return ok;
        }

        template <typename... Args>
        void appendFormat(std::string& output, std::format_string<Args...> format, Args&&... args)
        {
            std::format_to(std::back_inserter(output), format, std::forward<Args>(args)...);
        }

        void appendCppBytes(std::string& output, std::vector<std::uint8_t> const& data)
        {
            for (std::size_t i = 0; i < data.size(); ++i)
            {
                output += i % 16 == 0 ? "\n            " : " ";
                appendFormat(output, "0x{:02x},", static_cast<int>(data[i]));
            }
        }

        auto writeCpp(std::vector<LoadedResource> const& resources) -> std::unique_ptr<std::string>
        {
            auto output = std::make_unique<std::string>();
            output->append("// Auto-generated by rcc. Do not edit.\n");
            output->append("\n");
            output->append("#include <algorithm>\n");
            output->append("#include <array>\n");
            output->append("#include <aw/core/resource.hxx>\n");
            output->append("#include <cstdint>\n");
            output->append("#include <optional>\n");
            output->append("#include <span>\n");
            output->append("#include <string_view>\n");
            output->append("\n");

            output->append("namespace resources\n");
            output->append("{\n");
            output->append("    using Resource = aw::core::Resource;\n");
            output->append("\n");
            output->append("    namespace detail\n");
            output->append("    {\n");

            for (std::size_t i = 0; i < resources.size(); ++i)
            {
                appendFormat(*output, "        // {}\n", resources[i].path);
                appendFormat(*output, "        inline constexpr std::array<std::uint8_t, {}> resource{}{{", resources[i].data.size(), i);
                appendCppBytes(*output, resources[i].data);
                output->append("\n");
                output->append("        };\n");
                if (i + 1 < resources.size())
                {
                    output->append("\n");
                }
            }

            output->append("    } // namespace detail\n");
            output->append("\n");
            output->append("    /// Every embedded resource, sorted by path so that find() can bisect.\n");
            if (resources.empty())
            {
                output->append("    inline constexpr std::array<Resource, 0> all{};\n");
                output->append("\n");
            }
            else
            {
                appendFormat(*output, "    inline constexpr std::array<Resource, {}> all{{ {{\n", resources.size());
                for (std::size_t i = 0; i < resources.size(); ++i)
                {
                    appendFormat(*output, "        {{ \"{}\", detail::resource{} }},\n", resources[i].path, i);
                }
                output->append("    } };\n");
                output->append("\n");
            }

            output->append("    /// Look up a registered resource by path. A leading ':' is accepted.\n");
            output->append("    [[nodiscard]] auto find(std::string_view path) -> std::optional<Resource>\n");
            output->append("    {\n");
            output->append("        return aw::core::findResource(path);\n");
            output->append("    }\n");
            output->append("\n");
            output->append("    namespace detail\n");
            output->append("    {\n");
            output->append("        struct Registration\n");
            output->append("        {\n");
            output->append("            Registration() { awRegisterResourceData(nullptr, all.data(), all.size() * sizeof(Resource)); }\n");
            output->append("            ~Registration() { awUnregisterResourceData(nullptr, all.data(), all.size() * sizeof(Resource)); }\n");
            output->append("        };\n");
            output->append("\n");
            output->append("        inline Registration registration;\n");
            output->append("    } // namespace detail\n");
            output->append("} // namespace resources\n");
            return output;
        }

        void appendPythonBytes(std::string& output, std::vector<std::uint8_t> const& data)
        {
            for (std::size_t i = 0; i < data.size(); i += 32)
            {
                output += "\n        \"";
                auto const end = std::min<std::size_t>(i + 32, data.size());
                for (auto index = i; index < end; ++index)
                {
                    appendFormat(output, "{:02x}", static_cast<int>(data[index]));
                }
                output += '"';
            }
        }

        auto writePython(std::vector<LoadedResource> const& resources) -> std::unique_ptr<std::string>
        {
            auto output = std::make_unique<std::string>();
            output->append("# Auto-generated by rcc. Do not edit.\n");
            output->append("\n");
            output->append("RESOURCES: dict[str, bytes] = {\n");
            for (auto const& resource : resources)
            {
                appendFormat(*output, "    \"{}\": bytes.fromhex(", resource.path);
                if (resource.data.empty())
                {
                    output->append("\"\"");
                }
                else
                {
                    appendPythonBytes(*output, resource.data);
                }
                output->append("\n    ),\n");
            }

            output->append("}\n");
            output->append("\n");
            output->append("\n");
            output->append("def find(path: str) -> bytes | None:\n");
            output->append("    \"\"\"Look up a resource by path. A leading ':' is accepted, so ':/path' lookups work.\"\"\"\n");
            output->append("    return RESOURCES.get(path[1:] if path.startswith(\":\") else path)\n");
            return output;
        }
    } // namespace

    auto parseLanguage(std::string_view name) -> std::optional<Language>
    {
        if (name == "cpp")
        {
            return Language::Cpp;
        }
        if (name == "python")
        {
            return Language::Python;
        }
        return std::nullopt;
    }

    auto generate(Manifest const& manifest, std::filesystem::path const& baseDir, Language language) -> std::unique_ptr<std::string>
    {
        std::vector<LoadedResource> resources;
        if (!loadResources(manifest, baseDir, resources))
        {
            return nullptr;
        }

        switch (language)
        {
        case Language::Cpp:
            return writeCpp(resources);
        case Language::Python:
            return writePython(resources);
        }

        return nullptr;
    }
} // namespace aw::rcc
